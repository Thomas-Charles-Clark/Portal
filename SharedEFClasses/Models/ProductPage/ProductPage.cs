using Newtonsoft.Json;

using SharedEFClasses.Models.General;
using SharedEFClasses.Models.Products;

using System;
using System.Collections.Generic;
using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace SharedEFClasses.Models
{
    [Table("ProductPage", Schema = "dbo")]
    public class ProductPage
    {
        [Key]
        public int ProductPageID { get; set; }

        public byte TemplateID { get; set; }

        [StringLength(100)]
        public string Name { get; set; }

        [StringLength(70)]
        public string Heading { get; set; }

        [StringLength(70)]
        public string SubHeading { get; set; }

        [StringLength(3000)]
        public string Description { get; set; }

        [StringLength(100)]
        public string URLkeywords { get; set; }

        [StringLength(100)]
        public string TitleTag { get; set; }

        [StringLength(155)]
        public string MetaDescription { get; set; }

        public byte BrandID { get; set; }

        public byte ProductTypeID { get; set; }

        public short LaunchID { get; set; }

        public DateTime? OnDate { get; set; }

        public DateTime? OffDate { get; set; }

        public DateTime? DeletedDT { get; set; }

        public DateTime CreatedDT { get; set; }

        public DateTime? ModifiedDT { get; set; }

        public long? ColonyMetaCategoryID { get; set; }

        public bool New { get; set; }

        public byte AlternateColourwaySortOrder { get; set; }

        [StringLength(36)]
        public string FurnitureDimensions { get; set; }

        [StringLength(36)]
        public string FurnitureCutOut { get; set; }

        public bool FurnitureFabricOptions { get; set; }

        public bool FurnitureLeatherOptions { get; set; }

        public bool FurnitureLegStyles { get; set; }

        public bool FurnitureLegFinishes { get; set; }

        public bool FurnitureStitchingOptions { get; set; }

        public bool? Deleted { get; set; }

        public short? BrochureID { get; set; }

        public int? SortOrder { get; set; }

        public byte? ColourID { get; set; }

        public bool Clearance { get; set; }

        public short? ModularProductID { get; set; }

        public DateTime? AutoGenerateDT { get; set; }

        public int? MerchandiserID { get; set; }

        public int? SearchSortOrder { get; set; }

        [StringLength(255)]
        public string SearchKeywords { get; set; }

        public byte? PatternID { get; set; }

        [StringLength(255)]
        public string FurniturePDF { get; set; }

        public byte? TradeDiscountPercentage { get; set; }

        [StringLength(1)]
        public string TradeDiscountOperator { get; set; }

        /// <summary>
        /// NULL = Both; 0 = Retail Only; 1 = Trade Only
        /// </summary>
        public bool? TradeSwitch { get; set; }

        public int? CanonicalProductPageID { get; set; }

        public bool? TradeSwitchBackup { get; set; }

        [StringLength(70)]
        public string ShortHeading { get; set; }

        public short? CanonicalCollectionID { get; set; }

        [StringLength(1)]
        public string CanonicalContentType { get; set; }

        [ForeignKey("BrandID")]
        [InverseProperty("ProductPages")]
        public virtual Brand Brand { get; set; }

        [ForeignKey("CanonicalCollectionID")]
        [InverseProperty("CanonForProductPages")]
        public virtual Collection CanonicalCollection { get; set; }

        [ForeignKey("ColourID")]
        [InverseProperty("ProductPages")]
        public virtual Colour Colour { get; set; }

        [ForeignKey("LaunchID")]
        [InverseProperty("ProductPages")]
        public virtual Launch Launch { get; set; }

        [ForeignKey("PatternID")]
        [InverseProperty("ProductPages")]
        public virtual Pattern Pattern { get; set; }

        [ForeignKey("ProductTypeID")]
        [InverseProperty("ProductPages")]
        public virtual ProductType ProductType { get; set; }

        [InverseProperty("ProductPage")]
        public virtual ICollection<ProductPage_Attribute> Attributes { get; set; }

        [JsonIgnore]
        [InverseProperty("ProductPage")]
        public virtual ICollection<Product> Products { get; set; }
    }
}
