        //
        // POST: /Account/ForgotPassword
        [HttpPost]
        [AllowAnonymous]
        [ValidateAntiForgeryToken]
        public async Task<ActionResult> ForgotPassword(ForgotPasswordViewModel model)
        {
            if (ModelState.IsValid)
            {
                var user = await UserManager.FindByNameAsync(model.Email);
                if (user == null || !user.Roles.Any())
                {
                    // Don't reveal that the user does not exist, or is not confirmed, or has no roles
                    return View("ForgotPasswordConfirmation");
                }

                // For more information on how to enable account confirmation and password reset please visit http://go.microsoft.com/fwlink/?LinkID=320771
                // Send an email with this link
                string code = await signInManager.UserManager.GeneratePasswordResetTokenAsync(user.Id);
                var callbackUrl = Url.Action("ResetPassword", "Account", new { userId = user.Id, code = code }, protocol: Request.Url.Scheme);

                #pragma warning disable 4014
                System.Threading.Tasks.Task.Factory.StartNew(() =>
                {
                    UserManager.EmailService.SendAsync(new IdentityMessage()
                    {
                        Destination = user.Email,
                        Body = $"<p class='hello'>Hello, {user.FullName ?? user.Email}</p><p>Please reset your DG Portal password by clicking <a href=\"{callbackUrl}\">here</a></p>",
                        Subject = "Reset Password - Designers Guild Portal"
                    });
                });
                #pragma warning restore 4014

                return RedirectToAction("ForgotPasswordConfirmation", "Account");
            }

            // If we got this far, something failed, redisplay form
            return View(model);
        }

